/**
 * Fails the build if the files next-sitemap used to generate are still present.
 *
 * The sitemap and robots.txt are now produced by src/app/sitemap.ts and
 * src/app/robots.ts. A file left in public/ is served in preference to the route
 * of the same name, so a leftover public/robots.txt would quietly hide the new
 * one - the build would succeed and the section sitemaps would never be
 * announced to any crawler. That is the kind of failure nobody notices for
 * months, so it is made loud here instead.
 */
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const STALE = [
  "public/robots.txt",
  "public/sitemap.xml",
  "public/sitemap-0.xml",
  "next-sitemap.config.js",
];

const found = STALE.filter((rel) => existsSync(path.join(REPO, rel)));

if (found.length) {
  console.error(
    [
      "",
      "Stale next-sitemap output is still in the working tree:",
      ...found.map((rel) => `  ${rel}`),
      "",
      "robots.txt and the sitemaps are generated by src/app/robots.ts and",
      "src/app/sitemap.ts now. A file in public/ wins over the route of the",
      "same path, so these must go or the new sitemaps are never served.",
      "",
      `  git rm ${found.join(" ")}`,
      "",
    ].join("\n"),
  );
  process.exit(1);
}
